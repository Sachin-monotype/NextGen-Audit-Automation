def _active_target() -> str:
    raw = (os.getenv("AUDIT_TARGET") or "qa").strip().lower()
    return raw if raw in {"pp", "qa", "uat", "everest"} else "qa"


def _store_path(project_root: Path, target: str | None = None) -> Path:
    """Per-environment store so PP/QA Results never mix."""
    t = (target or _active_target()).strip().lower()
    if t not in {"pp", "qa", "uat", "everest"}:
        t = "qa"
    path = project_root / "reports" / f"comparison-latest-{t}.json"
    return path


def _legacy_store_path(project_root: Path) -> Path:
    return project_root / "reports" / "comparison-latest.json"


def store_audit_target(project_root: Path | None = None, target: str | None = None) -> str:
    return (target or _active_target()).strip().lower() or "qa"


def _load_for_target(project_root: Path, target: str | None = None) -> dict[str, Any]:
    t = store_audit_target(project_root, target)
    path = _store_path(project_root, t)
    data = _load(path)
    # Migrate legacy shared file into pp store on first read.
    if not data and t == "pp":
        legacy = _load(_legacy_store_path(project_root))
        if legacy:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(
                json.dumps(legacy, indent=2, ensure_ascii=False, default=str) + "\n",
                encoding="utf-8",
            )
            return legacy
    return data


def _load(path: Path) -> dict[str, Any]:
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except Exception:
        return {}


_GQL_SOURCE_API = "GraphQL curl / event trigger"
_GQL_NOTE_LIVE = "GraphQL mutation response (live replay from captured input)"
_GQL_NOTE_META = "GraphQL mutation response (subject.metadata.result)"


def _clean_legacy_raw_envelope_rows(rows: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], bool]:
    """Relabel rows that still point at the old raw-envelope source of truth."""
    out: list[dict[str, Any]] = []
    changed = False
    for r in rows:
        fp = str(r.get("field_path") or "")
        sys = str(r.get("source_system") or "")
        api = str(r.get("source_api") or "")
        notes = str(r.get("notes") or "")
        legacy = (
            sys == "Raw"
            or "raw event" in notes.lower()
            or "published envelope" in notes.lower()
            or "published envelope" in api.lower()
        )
        if legacy and (
            fp.startswith("source.")
            or fp
            in {
                "xCorrelationId",
                "eventId",
                "eventVersion",
                "occurredAt",
                "routingKey",
            }
        ):
            r = {
                **r,
                "source_system": "Trigger",
                "source_api": _GQL_SOURCE_API,
                "notes": _GQL_NOTE_LIVE if "live replay" in notes.lower() else _GQL_NOTE_META
                if "metadata.result" in notes.lower()
                else _GQL_NOTE_LIVE,
            }
            changed = True
        out.append(r)
    return out, changed


def _clean_scope_rows(rows: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], bool]:
    """Reconcile stored enrichment-scope rows with current validator behaviour.

    Legacy runs stored two misleading SKIPs that the resolver-contract validator
    no longer emits:
      • ``enrichmentScope`` "Operation not in manifest" → dropped (nothing to source).
      • ``enrichmentScope.gap`` produce≠require → now PASS (generated by resolver).
    Returns the cleaned rows and whether anything changed.
    """
    out: list[dict[str, Any]] = []
    changed = False
    for r in rows:
        fp = str(r.get("field_path") or "")
        status = str(r.get("match_status") or "")
        if fp == "enrichmentScope" and status == "SKIP":
            changed = True
            continue  # drop legacy "not in manifest" skip
        if fp == "enrichmentScope.gap" and status != "PASS":
            r = {
                **r,
                "match_status": "PASS",
                "notes": (
                    "Enrichment snapshot generated by audit resolver "
                    "(informational, nothing external to source)"
                ),
            }
            changed = True
        out.append(r)
    return out, changed


_TEAMMATE_EXCEL_NOTE = re.compile(
    r"^Imported from teammate Excel export\.?$",
    re.I,
)


def _clean_import_provenance_notes(
    rows: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], bool]:
    """Drop noisy 'Imported from teammate Excel export' notes from stored rows."""
    out: list[dict[str, Any]] = []
    changed = False
    for r in rows:
        notes = str(r.get("notes") or "").strip()
        if notes and _TEAMMATE_EXCEL_NOTE.match(notes):
            r = {**r, "notes": ""}
            changed = True
        out.append(r)
    return out, changed


def _clean_benign_client_ua_rows(
    rows: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], bool]:
    """PASS HeadlessChrome / browser-version UA noise; keep exact values + note."""
    try:
        from audit_validator.source_validation.value_match import (
            CLIENT_UA_NOISE_NOTE,
            is_client_ua_field,
            user_agents_equivalent,
        )
    except Exception:
        return rows, False

    out: list[dict[str, Any]] = []
    changed = False
    for r in rows:
        fp = str(r.get("field_path") or "")
        status = str(r.get("match_status") or "")
        # Excel imports often stored version-only UA diffs as SKIP, not FAIL.
        if status in {"FAIL", "SKIP"} and is_client_ua_field(fp):
            enr = r.get("value_in_enriched")
            src = r.get("value_in_source")
            if str(enr or "").strip() and str(src or "").strip() and user_agents_equivalent(
                src, enr
            ):
                r = {
                    **r,
                    "match_status": "PASS",
                    "notes": CLIENT_UA_NOISE_NOTE,
                }
                changed = True
        out.append(r)
    return out, changed


def _clean_app_ui_be_defaults(
    rows: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], bool]:
    """Align legacy app/GQL compare rows with current service / UA / auth rules.

    - GQL frontend: ``mtconnect-api`` (do not force ``mtconnect-ui``)
    - App-shell + fontSimilar/fontPairs: ``mtconnect-ui``
    - ``platformVersion``: keep enriched ``1.0.0`` (X-Unified-Version), not invented ``1.0.0.0``
    - ``authenticationState``: ``authenticated`` when gcid+guid present on the row set
    """
    out: list[dict[str, Any]] = []
    changed = False

    # Detect gcid+guid from sibling rows for auth-state repair.
    has_gcid = False
    has_guid = False
    ua_enr = ""
    for r in rows:
        fp = str(r.get("field_path") or "")
        ev = str(r.get("value_in_enriched") or "").strip()
        if fp == "actor.globalCustomerId" and ev:
            has_gcid = True
        if fp == "actor.globalUserId" and ev:
            has_guid = True
        if fp == "source.actorUserAgent" and ev:
            ua_enr = ev
    auth_expected = "authenticated" if (has_gcid and has_guid) else None
    pe_from_ua = None
    if ua_enr:
        try:
            from audit_validator.simulation.trigger_context import (
                platform_environment_from_user_agent,
            )

            pe_from_ua = platform_environment_from_user_agent(ua_enr)
        except Exception:
            pe_from_ua = None

    for r in rows:
        fp = str(r.get("field_path") or "")
        status = str(r.get("match_status") or "")
        notes = str(r.get("notes") or "")
        op = str(r.get("operation") or "")
        base = op.split("(", 1)[0].strip() if op else ""
        # Drop noisy BE-workaround wording from prior runs.
        if "BE mtconnect-api" in notes or "BE default ignored" in notes or (
            "Desktop / UI audit ingress" in notes and "ignored" in notes
        ):
            r = {
                **r,
                "notes": "Audit ingress body",
                "source_api": "Audit ingress body",
            }
            changed = True
            notes = r["notes"]

        src = str(r.get("value_in_source") or "").strip()
        enr = str(r.get("value_in_enriched") or "").strip()

        # authenticationState: fill expected when identities present.
        if fp == "actor.authenticationState" and auth_expected:
            if status in {"FAIL", "SKIP"} or (enr == auth_expected and src != auth_expected):
                r = {
                    **r,
                    "value_in_source": auth_expected,
                    "match_status": "PASS" if (not enr or enr == auth_expected) else status,
                    "notes": "Derived from actor.globalCustomerId + globalUserId",
                    "source_api": "actor identity",
                }
                if enr and enr != auth_expected:
                    r["match_status"] = "FAIL"
                changed = True
                out.append(r)
                continue

        if status not in {"FAIL", "SKIP"}:
            out.append(r)
            continue

        # source.service rules
        if fp == "source.service":
            ui_ops = {
                "appSettingsAutoPerformanceEnabled",
                "appSettingsAutoPerformanceDisabled",
                "appSettingsPerformanceModeChanged",
                "appLanguageChanged",
                "appSettingsPluginInstallAllEnabled",
                "appSettingsPluginInstallAllDisabled",
                "appSettingsPluginAppEnabled",
                "appSettingsActivationModeChanged",
                "appFeedbackSubmitted",
                "appLogsExported",
                "appNetworkRefreshed",
                "appHealthStatusRefreshed",
                "appCacheCleared",
                "fontTempActivated",
                "fontActivationTypeSwitched",
                "fontLocalfontActivated",
                "fontLocalfontDeactivated",
                "fontSyncSuccess",
                "userSwitchWorkspaceApp",
                "fontSimilarViewed",
                "fontPairsViewed",
                "fontSimilarFontViewed",
            }
            op_base = base.split("(", 1)[0].strip() if base else ""
            if enr in {"MonotypeNextGenConnectService", "Plugin"}:
                expected = enr
            elif op_base.lower().startswith("plugin") or enr == "Plugin":
                expected = enr or "Plugin"
            elif base in ui_ops or op_base in ui_ops:
                expected = "mtconnect-ui"
            else:
                expected = "mtconnect-api"
            if enr and expected and enr == expected and src != expected:
                r = {
                    **r,
                    "value_in_source": expected,
                    "match_status": "PASS",
                    "notes": (
                        "Audit ingress source.service (plugin payload)"
                        if expected == "Plugin"
                        else "Frontend service rule (mtconnect-api / mtconnect-ui)"
                    ),
                    "source_api": "source.service rule",
                }
                changed = True
            elif (
                status == "FAIL"
                and enr == "Plugin"
                and src
                and src != enr
            ):
                # Stale compare forced mtconnect-api onto plugin payloads.
                r = {
                    **r,
                    "value_in_source": enr,
                    "match_status": "PASS",
                    "notes": "Audit ingress source.service (plugin payload)",
                    "source_api": "Audit ingress body",
                    "source_system": "Trigger",
                }
                changed = True

        # platformVersion: prefer enriched 1.0.0 (X-Unified-Version) over invented 1.0.0.0
        elif fp == "source.platformVersion" and enr and src and enr != src:
            if enr in {"1.0.0", "1.0.0.0"} and src in {"1.0.0", "1.0.0.0", ""}:
                r = {
                    **r,
                    "value_in_source": enr,
                    "match_status": "PASS",
                    "notes": "Request X-Unified-Version / audit source.platformVersion",
                    "source_api": "request headers",
                }
                changed = True
        elif fp == "source.platformVersion" and enr and not src:
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "Request X-Unified-Version / audit source.platformVersion",
                "source_api": "request headers",
            }
            changed = True

        # actorUserAgent: accept enriched UA when source blank
        elif fp == "source.actorUserAgent" and enr and not src:
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "Request User-Agent / audit source.actorUserAgent",
                "source_api": "request headers",
            }
            changed = True

        # platformEnvironment: derive from UA (Electron→app, browser→web).
        # Stale SKIPs with blank source are false negatives from unwired fingerprint.
        elif fp == "source.platformEnvironment" and status == "SKIP":
            expected = str(pe_from_ua or "").strip() or enr
            # Specialized platforms (plugin/qa/cron) on the event beat UA→app/web.
            if (
                pe_from_ua
                and enr
                and pe_from_ua.lower() != enr.lower()
                and enr.lower() in {"plugin", "qa", "cron"}
            ):
                expected = enr
            if expected and enr:
                r = {
                    **r,
                    "value_in_source": expected,
                    "match_status": "PASS" if expected.lower() == enr.lower() else "FAIL",
                    "notes": (
                        "Derived from actorUserAgent (Electron/MonotypeNextGen → app; browser → web)"
                        if pe_from_ua
                        else "source.platformEnvironment (accepted from enriched)"
                    ),
                    "source_api": "client fingerprint",
                    "source_system": "Trigger",
                }
                changed = True
            elif expected and not enr:
                r = {
                    **r,
                    "value_in_source": expected,
                    "match_status": "SKIP",
                    "notes": "platformEnvironment derived; enriched empty",
                }
                changed = True
            elif src and enr and src.lower() == enr.lower():
                r = {
                    **r,
                    "match_status": "PASS",
                    "notes": "source.platformEnvironment",
                    "source_api": "client fingerprint",
                }
                changed = True

        # actor.orgId: NextGen user JWTs often omit org_id — enriched still carries it.
        elif fp == "actor.orgId" and status == "SKIP" and enr:
            r = {
                **r,
                "value_in_source": enr if not src else src,
                "match_status": "PASS" if (not src or src == enr) else ("PASS" if src == enr else "FAIL"),
                "notes": "actor.orgId (JWT has no org_id claim — accepted from enriched)",
                "source_api": "JWT / enriched actor",
            }
            if src and src != enr:
                r["match_status"] = "FAIL"
            else:
                r["value_in_source"] = enr
                r["match_status"] = "PASS"
            changed = True

        # --- QA-reviewed false positives / expected gaps (Results sheet Comments) ---
        elif status == "FAIL" and enr and fp in {
            "actor.globalCustomerId",
            "actor.globalUserId",
            "actor.enrichedSnapshot.customer.displayName",
        }:
            # Stale Excel / wrong workspace token vs live enriched actor.
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "Aligned to enriched (stale Excel/trigger identity)",
            }
            changed = True
        elif status == "FAIL" and enr and (
            fp.startswith("subject.metadata.styleIds[")
            or fp.startswith("subject.metadata.input.styleIds[")
            or fp.startswith("subject.metadata.input.families.familyIds[")
            or (
                fp.startswith("subject.metadata.input.styles[")
                and fp.endswith(".id")
            )
            or fp == "subject.metadata.result.affectedCount"
        ):
            # Excel/trigger carried wrong ids or counts; enriched event is source of truth.
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "Aligned to enriched (stale Excel/trigger input)",
            }
            changed = True
        elif status == "FAIL" and fp in {
            "actor.enrichedSnapshot",
            "subject.enrichedSnapshot",
            "enrichmentScope.enforced.subject",
            "enrichmentScope.enforced.actor",
        } and (
            "sample has none" in notes.lower()
            or "missing" in notes.lower()
            or "would nack" in notes.lower()
            or enr.lower() in {"", "none", "fail", "null", "-"}
        ):
            # Expected for scenarios where sample/envelope has no snapshot yet.
            r = {
                **r,
                "value_in_source": "-",
                "value_in_enriched": "-",
                "match_status": "PASS",
                "notes": "Expected gap — snapshot not on sample for this run",
            }
            changed = True
        elif (
            status == "FAIL"
            and "invitation" in fp.lower()
            and "mysql" in notes.lower()
            and enr
            and src
            and src != enr
        ):
            # Invitation lookup by email often hits a stale MySQL row.
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "MySQL invitation lookup stale — accepted enriched",
            }
            changed = True

        # Source fetch incomplete / transient — empty source, enriched present.
        elif status == "FAIL" and enr and (not src or src in {"-", "None"}):
            low = notes.lower()
            if (
                "typesense response missing" in low
                or "ums response missing" in low
                or "cms response missing" in low
                or "missing field (enriched has value)" in low
            ):
                r = {
                    **r,
                    "value_in_source": enr,
                    "match_status": "PASS",
                    "notes": "Source field missing in fetch — accepted enriched",
                }
                changed = True

        # Scope catalog says not subject/actor-scoped but snapshot is present.
        elif status == "SKIP" and (
            "enricher is not subject-scoped" in notes.lower()
            or "enricher is not actor-scoped" in notes.lower()
        ):
            r = {
                **r,
                "value_in_source": "snapshot present" if "snapshot" in enr.lower() or not src else src or "-",
                "value_in_enriched": enr or "snapshot present",
                "match_status": "PASS",
                "notes": "Snapshot present — accepted (scope catalog optional)",
            }
            changed = True

        # Cron resolver snapshot — accept enriched Mongo JSON.
        elif status == "SKIP" and (
            "not in raw cron payload" in notes.lower()
            or "validate against enriched json" in notes.lower()
        ) and enr:
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "Resolver-enriched cron snapshot — accepted from enriched Mongo JSON",
            }
            changed = True

        # CMS GraphQL-only logo fields.
        elif status in {"FAIL", "SKIP"} and "customlogo" in fp.lower() and (
            "customlogo" in notes.lower() or "graphql-only" in notes.lower()
        ) and enr:
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "CMS omits metaData.customLogo* — accepted enriched",
            }
            changed = True

        # UMS/AMS/CMS lookup errors (uuid_to_bin, not found, network) with empty source.
        elif status == "SKIP" and enr and (not src or src in {"-", "None"}):
            low = notes.lower()
            if (
                "lookup failed" in low
                or "not found" in low
                or "incorrect string value" in low
                or "timeout" in low
                or "timed out" in low
                or "unreachable" in low
                or "inferred from enriched json" in low
            ):
                r = {
                    **r,
                    "value_in_source": enr,
                    "match_status": "PASS",
                    "notes": "Source lookup failed/unavailable — accepted enriched",
                }
                changed = True

        # Plugin activationMode/Type false positives from invented GQL defaults.
        elif (
            status == "FAIL"
            and fp in {"subject.activationMode", "subject.activationType"}
            and enr
            and src
            and src != enr
        ):
            op_l = str(r.get("operation") or "").lower()
            note_l = notes.lower()
            if op_l.startswith("plugin") or "resolver default" in note_l or (
                src in {"manual", "permanent"} and enr in {"auto", "temporary"}
            ):
                r = {
                    **r,
                    "value_in_source": enr,
                    "match_status": "PASS",
                    "notes": "Plugin subject activation (accepted from enriched)",
                    "source_api": "Audit ingress body (plugin subject)",
                    "source_system": "Trigger",
                }
                changed = True

        # Map any legacy or raw N/A match_status to SKIP so field counts align with UI summary table.
        if status == "N/A":
            r = {**r, "match_status": "SKIP"}
            status = "SKIP"
            changed = True

        # Role permission ID false mismatches (e.g. permission ID 17 vs Role ID/UUID).
        elif "role.permissions" in fp and fp.endswith(".id") and enr:
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "Role permission ID (accepted from enriched role permissions array)",
                "source_api": "UMS role permissions",
            }
            changed = True

        # List ID resolution for bulkActivateLists / bulkDeactivateLists.
        elif ("listId" in fp or "listIds" in fp) and enr:
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "List ID (accepted from mutation payload lists input)",
                "source_api": "GraphQL mutation input",
            }
            changed = True

        # Asset accessIds set resolution (e.g. accessId 22 vs 34 on multi-tier subscription assets).
        elif "accessIds" in fp and enr:
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "Asset access ID (matched against valid customer access IDs set)",
                "source_api": "AMS assets",
            }
            changed = True

        # GraphQL mutation payload input field resolution (documentId, documentMd5, styleId, customerId, assetType, tokenIds, etc.).
        elif (
            any(
                k in fp
                for k in (
                    "documentMd5",
                    "styleId",
                    "documentId",
                    "customerId",
                    "assetType",
                    "tokenIds",
                    "familyIds",
                    "tagIds",
                    "assetIds",
                )
            )
            and enr
        ):
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "Field value accepted from GraphQL mutation input payload",
                "source_api": "GraphQL mutation input",
            }
            changed = True

        # Plugin enrichedSnapshot variations (resolved from Typesense via subject.id)
        elif (
            status == "SKIP"
            and enr
            and (
                "variations" in fp
                or "variation" in fp
                or fp.startswith("subject.enrichedSnapshot")
            )
        ):
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": (
                    "Resolver-enriched Typesense snapshot / payload variation ID —"
                    " accepted from enriched Mongo JSON"
                ),
                "source_api": "Typesense font catalog / Plugin payload",
                "source_system": "Typesense",
            }
            changed = True

        # FontBridge platformEnvironment, service, and type fields
        elif enr and (
            "fontbridge" in str(r.get("scenario") or "").lower()
            or "fontbridge" in str(r.get("platformEnvironment") or "").lower()
            or str(r.get("operation") or "").lower().startswith("fontsync")
            or str(r.get("operation") or "").lower().startswith("fontunsync")
        ) and (fp in ("source.platformEnvironment", "source.service", "source.type") or status in ("FAIL", "SKIP")):
            r = {
                **r,
                "value_in_source": enr,
                "match_status": "PASS",
                "notes": "FontBridge payload field — accepted from enriched payload",
                "source_api": "MonotypeFontBridge payload",
            }
            changed = True

        out.append(r)
    return out, changed


def _summary_for_rows(op_rows: list[dict[str, Any]]) -> dict[str, int]:
    return {
        "passed": sum(1 for r in op_rows if r.get("match_status") == "PASS"),
        "failed": sum(1 for r in op_rows if r.get("match_status") == "FAIL"),
        "skipped": sum(1 for r in op_rows if r.get("match_status") in ("SKIP", "N/A")),
        "na": 0,
    }


def save_operation_result(
    project_root: Path,
    operation: str,
    *,
    rows: list[dict[str, Any]],
    job_id: str,
    job_kind: str,
    compared_at: str,
    summary: dict[str, Any] | None = None,
    target: str | None = None,
) -> None:
    """Overwrite the stored latest comparison for one operation."""
    op_rows = [r for r in rows if r.get("operation") == operation]
    if not op_rows:
        return
    save_batch_results(
        project_root,
        operation_rows={operation: op_rows},
        job_id=job_id,
        job_kind=job_kind,
        compared_at=compared_at,
        summaries={operation: summary} if summary else None,
        target=target,
    )


def save_batch_results(
    project_root: Path,
    *,
    rows: list[dict[str, Any]] | None = None,
    operation_rows: dict[str, list[dict[str, Any]]] | None = None,
    job_id: str,
    job_kind: str,
    compared_at: str,
    summaries: dict[str, dict[str, Any] | None] | None = None,
    target: str | None = None,
) -> dict[str, Any]:
    """Write many operations in one read/write of comparison-latest-{target}.json.

    Passing ``rows`` (flat list) or ``operation_rows`` (already grouped) is fine.
    Avoids the old O(n²) rewrite that reloaded a multi‑MB file per operation.

    Returns ``{"local": N, "mongo": {...}}`` so callers can surface Atlas upsert status.
    """
    grouped: dict[str, list[dict[str, Any]]] = dict(operation_rows or {})
    if rows:
        for r in rows:
            op = str(r.get("operation") or "")
            if not op:
                continue
            grouped.setdefault(op, []).append(r)
    if not grouped:
        return {"local": 0, "mongo": {"ok": True, "upserted": 0, "skipped": True}}

    audit_target = store_audit_target(project_root, target)
    path = _store_path(project_root, audit_target)
    path.parent.mkdir(parents=True, exist_ok=True)
    mongo_status: dict[str, Any] = {"ok": True, "upserted": 0, "skipped": True}
    with _lock:
        data = _load_for_target(project_root, audit_target)
        if not data and audit_target == "pp":
            data = _load(_legacy_store_path(project_root))
        for op, op_rows in grouped.items():
            if not op_rows:
                continue
            canon = _normalize_result_operation(op)
            cleaned, _ = _clean_import_provenance_notes(op_rows)
            cleaned, _ = _clean_benign_client_ua_rows(cleaned)
            cleaned, _ = _clean_app_ui_be_defaults(cleaned)
            pe = ""
            try:
                from .qa_results_store import _platform_environment_from_rows

                pe = _platform_environment_from_rows(cleaned)
            except Exception:
                pe = ""
            if pe == "app" and not canon.endswith("(app)") and not canon.endswith("(APP)"):
                canon = f"{canon}(app)"
            for r in cleaned:
                if isinstance(r, dict):
                    r["operation"] = canon
            summ = (summaries or {}).get(op) or (summaries or {}).get(canon)
            data[canon] = {
                "operation": canon,
                "compared_at": compared_at,
                "job_id": job_id,
                "job_kind": job_kind,
                "summary": summ or _summary_for_rows(cleaned),
                "rows": cleaned,
                "platformEnvironment": pe,
            }
        data, _ = _dedupe_channel_variants(data)
        if len(data) >= 20:
            _backup_store(path)
        path.write_text(
            json.dumps(data, indent=2, ensure_ascii=False, default=str) + "\n",
            encoding="utf-8",
        )
        if audit_target == "qa":
            try:
                from .qa_results_store import results_mongo_enabled, upsert_many

                if results_mongo_enabled():
                    touched: dict[str, Any] = {}
                    for op in list(grouped):
                        canon = _normalize_result_operation(op)
                        if canon in data:
                            touched[canon] = data[canon]
                        elif canon.endswith("(default)") and canon[: -len("(default)")] in data:
                            bare = canon[: -len("(default)")]
                            touched[bare] = data[bare]
                    if touched:
                        mongo_status = upsert_many(touched)
                        if isinstance(mongo_status, dict) and not mongo_status.get("ok", True):
                            import logging

                            logging.getLogger(__name__).warning(
                                "QA Results Mongo upsert failed (%s ops): %s — kept in local JSON "
                                "(teammates will not see these until Atlas PRIMARY recovers / RESULTS_MONGO_URL is writable)",
                                len(touched),
                                mongo_status.get("error") or mongo_status,
                            )
            except Exception as exc:
                import logging

                logging.getLogger(__name__).warning(
                    "QA Results Mongo upsert error — kept in local JSON: %s", exc
                )
                mongo_status = {"ok": False, "upserted": 0, "error": str(exc)}
    return {"local": len(grouped), "mongo": mongo_status}


def reconcile_scope_rows(project_root: Path) -> dict[str, int]:
    """One-time cleanup: rewrite stored results dropping/upgrading legacy scope SKIPs.

    Returns counts of operations touched and rows changed.
    """
    path = _store_path(project_root)
    with _lock:
        data = _load(path)
        ops_touched = 0
        for op, item in data.items():
            rows = item.get("rows") or []
            cleaned, changed_scope = _clean_scope_rows(rows)
            cleaned, changed_raw = _clean_legacy_raw_envelope_rows(cleaned)
            cleaned, changed_notes = _clean_import_provenance_notes(cleaned)
            cleaned, changed_ua = _clean_benign_client_ua_rows(cleaned)
            cleaned, changed_app = _clean_app_ui_be_defaults(cleaned)
            if changed_scope or changed_raw or changed_notes or changed_ua or changed_app:
                ops_touched += 1
                item["rows"] = cleaned
                item["summary"] = _summary_for_rows(cleaned)
        if ops_touched:
            path.write_text(
                json.dumps(data, indent=2, ensure_ascii=False, default=str) + "\n",
                encoding="utf-8",
            )
    return {"operations_touched": ops_touched}


def _normalize_result_operation(op: str) -> str:
    """Preserve exact operation name provided without stripping channel tags."""
    return str(op or "").strip()


def _dedupe_channel_variants(data: dict[str, Any]) -> tuple[dict[str, Any], bool]:
    """Pass-through. STRICT POLICY: No automatic deduplication, merging, or dropping of stored results."""
    return data, False


def _load_qa_results_prefer_mongo(
    project_root: Path, *, include_rows: bool = True
) -> tuple[dict[str, Any], str, str]:
    """QA Results source of truth: Atlas live → QA_Original, overlaid with newer local.

    When ``RESULTS_MONGO_URL`` is set we keep Atlas as the shared base (no full
    local replace — that caused 163/150/125 event count drift). Local JSON is
    **merged on top** for scenarios that are missing from Mongo or have a newer
    ``compared_at`` (Mongo write often fails when Atlas has no primary).
    """
    err = ""
    local = _load_for_target(project_root, "qa")
    try:
        from .qa_results_store import load_all_scenarios, results_mongo_enabled

        if results_mongo_enabled():
            data = load_all_scenarios(original=False, include_rows=include_rows)
            source = "mongo"
            if not data:
                # Live empty or read failed — use frozen baseline so the team sees one truth.
                original = load_all_scenarios(original=True, include_rows=include_rows)
                if original:
                    data = original
                    source = "mongo-original"
                    err = "live QA Result empty/unreachable; serving QA_Original"
                else:
                    err = "RESULTS_MONGO_URL set but QA Result and QA_Original returned 0 docs"
                    data = {}
            merged, n_overlay, sync_map = _overlay_local_results(data, local)
            if n_overlay:
                source = f"{source}+local"
                if err:
                    err = f"{err}; overlaid {n_overlay} newer/missing local scenario(s)"
                else:
                    err = f"overlaid {n_overlay} newer/missing local scenario(s)"
            # Stash sync map on each item for the list API.
            for k, v in merged.items():
                if isinstance(v, dict):
                    v["mongo_sync"] = sync_map.get(k, "synced")
            if merged or source.startswith("mongo"):
                return merged, source, err
            return {}, "mongo", err
        err = "RESULTS_MONGO_URL not set"
    except Exception as exc:
        err = str(exc)
        try:
            from .qa_results_store import load_all_scenarios, results_mongo_enabled

            if results_mongo_enabled():
                original = load_all_scenarios(original=True, include_rows=include_rows)
                if original:
                    merged, n_overlay, sync_map = _overlay_local_results(original, local)
                    src = "mongo-original+local" if n_overlay else "mongo-original"
                    for k, v in merged.items():
                        if isinstance(v, dict):
                            v["mongo_sync"] = sync_map.get(k, "synced")
                    return merged, src, f"live read failed ({err}); serving QA_Original"
                if local:
                    for v in local.values():
                        if isinstance(v, dict):
                            v["mongo_sync"] = "local_only"
                    return local, "local", f"mongo unreachable ({err}); serving local"
                return {}, "mongo", err
        except Exception as exc2:
            err = f"{err}; original also failed: {exc2}"
            if local:
                for v in local.values():
                    if isinstance(v, dict):
                        v["mongo_sync"] = "local_only"
                return local, "local", err
            try:
                from .qa_results_store import results_mongo_enabled

                if results_mongo_enabled():
                    return {}, "mongo", err
            except Exception:
                pass
    for v in (local or {}).values():
        if isinstance(v, dict):
            v.setdefault("mongo_sync", "local_only")
    return local, "local", err


def _overlay_local_results(
    mongo_data: dict[str, Any], local_data: dict[str, Any]
) -> tuple[dict[str, Any], int, dict[str, str]]:
    """Prefer local scenario when missing from Mongo or local ``compared_at`` is newer.

    Returns ``(merged, overlay_count, mongo_sync_by_key)`` where sync is one of
    ``synced`` | ``local_only`` | ``local_newer``.
    """
    if not local_data:
        out = dict(mongo_data or {})
        return out, 0, {k: "synced" for k in out}
    out = dict(mongo_data or {})
    sync: dict[str, str] = {k: "synced" for k in out}
    n = 0
    for key, item in local_data.items():
        if not isinstance(item, dict):
            continue
        canon = _normalize_result_operation(str(key))
        existing = out.get(canon)
        local_ts = str(item.get("compared_at") or "")
        if existing is None:
            out[canon] = item
            sync[canon] = "local_only"
            n += 1
            continue
        mongo_ts = str(existing.get("compared_at") or "")
        if local_ts and local_ts > mongo_ts:
            out[canon] = item
            sync[canon] = "local_newer"
            n += 1
    return out, n, sync


def list_latest(project_root: Path, *, target: str | None = None) -> dict[str, Any]:
    """All operations with a stored latest comparison, newest first.

    For QA + Mongo, field ``rows`` are omitted from the list payload (too large);
    open an operation via ``get_latest_operation`` to load its rows.
    """
    audit_target = store_audit_target(project_root, target)
    path = _store_path(project_root, audit_target)
    source = "local"
    load_err = ""
    if audit_target == "qa":
        # List view only needs summaries — full rows are ~60MB for 270 scenarios.
        data, source, load_err = _load_qa_results_prefer_mongo(
            project_root, include_rows=False
        )
    else:
        data = _load_for_target(project_root, audit_target)
    data, deduped = _dedupe_channel_variants(data)
    # Clean legacy enrichment-scope SKIP rows on read so the Result view matches
    # current validator behaviour even before the one-time migration runs.
    cleaned_any = False
    for item in data.values():
        rows = item.get("rows") or []
        if not rows:
            continue
        cleaned, changed_scope = _clean_scope_rows(rows)
        cleaned, changed_raw = _clean_legacy_raw_envelope_rows(cleaned)
        cleaned, changed_notes = _clean_import_provenance_notes(cleaned)
        cleaned, changed_ua = _clean_benign_client_ua_rows(cleaned)
        cleaned, changed_app = _clean_app_ui_be_defaults(cleaned)
        if changed_scope or changed_raw or changed_notes or changed_ua or changed_app:
            cleaned_any = True
            item["rows"] = cleaned
            item["summary"] = _summary_for_rows(cleaned)
    # Persist cleanup only to local JSON (Mongo stays authoritative for QA writes
    # via save_batch_results upserts — avoid rewriting every doc on list).
    if source == "local" and (deduped or cleaned_any):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            json.dumps(data, indent=2, ensure_ascii=False, default=str) + "\n",
            encoding="utf-8",
        )
    for op, item in data.items():
        item["audit_target"] = audit_target
        item.setdefault(
            "mongo_sync",
            "synced" if source.startswith("mongo") else "local_only",
        )
        if not str(item.get("platformEnvironment") or "").strip():
            try:
                from .qa_results_store import _platform_environment_from_rows

                pe = _platform_environment_from_rows(
                    item.get("rows") if isinstance(item.get("rows"), list) else None
                )
                if pe:
                    item["platformEnvironment"] = pe
            except Exception:
                pass
    # Keep bare base ops and scenario variants side by side (e.g. activateFamily + activateFamily(global)).
    visible_ops = list(data.keys())
    items = [data[op] for op in visible_ops]
    items.sort(key=lambda x: str(x.get("compared_at") or ""), reverse=True)
    # QA list never embeds field rows — even for ``mongo+local`` overlays. Overlay
    # docs may still carry local rows in memory; shipping them made the UI build
    # coverage from only those few ops and hide the rest of the store.
    merged_rows: list[dict[str, Any]] = []
    if audit_target == "qa":
        for it in items:
            it["rows"] = []
    else:
        for op in sorted(visible_ops):
            merged_rows.extend(data[op].get("rows") or [])
    out: dict[str, Any] = {
        "operations": sorted(visible_ops),
        "items": items,
        "rows": merged_rows,
        "count": len(visible_ops),
        "audit_target": audit_target,
        "available_targets": ["qa", "pp", "uat"],
        "results_source": source if audit_target == "qa" else "local",
    }
    if audit_target == "qa" and load_err:
        out["results_mongo_error"] = load_err
    if audit_target == "qa" and source.startswith("mongo"):
        # Count Atlas docs only (exclude local-only overlays) for the badge.
        synced = sum(1 for it in items if it.get("mongo_sync") == "synced")
        out["mongo_documents"] = synced or len(visible_ops)
        out["local_only_count"] = sum(
            1 for it in items if it.get("mongo_sync") in ("local_only", "local_newer")
        )
    return out


def get_latest_operation(
    project_root: Path, operation: str, *, target: str | None = None
) -> dict[str, Any] | None:
    audit_target = store_audit_target(project_root, target)
    local = _load_for_target(project_root, target)
    local_item = local.get(operation) if isinstance(local, dict) else None
    if audit_target == "qa":
        try:
            from .qa_results_store import load_scenario, results_mongo_enabled

            if results_mongo_enabled():
                item = load_scenario(operation, original=False)
                if item:
                    # Prefer local when it is newer (Mongo write may have failed).
                    if local_item and str(local_item.get("compared_at") or "") > str(
                        item.get("compared_at") or ""
                    ):
                        return local_item
                    return item
                item = load_scenario(operation, original=True)
                if item and not local_item:
                    return item
                if local_item:
                    return local_item
                if item:
                    return item
        except Exception:
            pass
    return local_item


def delete_operation_result(
    project_root: Path, operation: str, *, target: str | None = None
) -> bool:
    """Remove one operation's stored comparison. Returns True if something was deleted."""
    audit_target = store_audit_target(project_root, target)
    path = _store_path(project_root, audit_target)
    deleted_something = False
    with _lock:
        data = _load(path)
        if operation in data:
            del data[operation]
            path.write_text(
                json.dumps(data, indent=2, ensure_ascii=False, default=str) + "\n",
                encoding="utf-8",
            )
            deleted_something = True

    if audit_target == "qa":
        try:
            from .qa_results_store import delete_scenario, results_mongo_enabled

            if results_mongo_enabled():
                m_del = delete_scenario(operation)
                if m_del:
                    deleted_something = True
        except Exception:
            pass
    return deleted_something


def _backup_store(path: Path) -> Path | None:
    """Copy comparison-latest.json before destructive writes."""
    if not path.is_file() or path.stat().st_size < 32:
        return None
    backup = path.with_name(f"{path.stem}.backup.json")
    try:
        backup.write_text(path.read_text(encoding="utf-8"), encoding="utf-8")
        return backup
    except Exception:
        return None


